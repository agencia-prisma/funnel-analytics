import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const collectorDirectory = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const repositoryRoot = path.resolve(collectorDirectory, '../..');
const pixelDirectory = path.join(repositoryRoot, 'packages/pixel');
const pixelRequire = createRequire(path.join(pixelDirectory, 'package.json'));
const { build } = pixelRequire('esbuild');
const pixelPackage = JSON.parse(
  await readFile(path.join(pixelDirectory, 'package.json'), 'utf8'),
);

const result = await build({
  absWorkingDir: repositoryRoot,
  entryPoints: [path.join(pixelDirectory, 'src/browser-entry.ts')],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: ['es2020'],
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  charset: 'utf8',
  write: false,
});

const bundle = result.outputFiles[0]?.text;

if (!bundle) {
  throw new Error('PIXEL_BUNDLE_EMPTY');
}

const version = String(pixelPackage.version);
const generatedModule = [
  '// Generated by scripts/generate-pixel-script.mjs. Do not edit manually.',
  `export const PIXEL_SCRIPT_VERSION = ${JSON.stringify(version)};`,
  `export const PIXEL_SCRIPT_ETAG = ${JSON.stringify(`"pixel-sdk-v${version}"`)};`,
  `export const PIXEL_SCRIPT = ${JSON.stringify(`/* Funnel Analytics Pixel SDK v${version} */\n${bundle}`)};`,
  '',
].join('\n');

const outputPath = path.join(
  collectorDirectory,
  'src/pixel-script.generated.ts',
);
const currentModule = await readFile(outputPath, 'utf8').catch(() => null);

if (currentModule !== generatedModule) {
  await writeFile(outputPath, generatedModule, 'utf8');
}
